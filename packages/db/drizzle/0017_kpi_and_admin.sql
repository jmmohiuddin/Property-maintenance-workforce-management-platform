	FOR EACH ROW EXECUTE FUNCTION app_product_event_payments();--> statement-breakpoint

-- ── Contract events (G10 renewal rate) ──────────────────────────────────────
--
-- The `contracts` table has existed since 0000 with no UI; `CON-1`…`CON-10` are
-- being built in parallel. This trigger reads `status` and nothing else, so it
-- survives whatever columns that work adds.
CREATE OR REPLACE FUNCTION app_product_event_contracts() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
	IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
		RETURN NEW;
	END IF;
	PERFORM app_product_event(NEW.tenant_id, 'contract_status_changed', 'contract', NEW.id, jsonb_build_object(
		'from', OLD.status::text,
		'to', NEW.status::text,
		'annual_value_minor', (NEW.annual_value * 100)::bigint,
		'currency', NEW.currency,
		'ends_on', NEW.ends_on
	));
	RETURN NEW;
END
$$;--> statement-breakpoint

DROP TRIGGER IF EXISTS product_event_contracts ON public.contracts;--> statement-breakpoint
CREATE TRIGGER product_event_contracts
	AFTER UPDATE ON public.contracts
	FOR EACH ROW EXECUTE FUNCTION app_product_event_contracts();--> statement-breakpoint

-- ── ADM-7: the index the audit log viewer reads ─────────────────────────────
--
-- The viewer's default query is "this tenant, this table, newest first", and
-- the three existing indexes cannot serve it. `audit_log_tenant_time_idx` is
-- (tenant_id, occurred_at) with no table_name, so filtering to `invoices`
-- scans every row in the window; `audit_log_record_idx` is (table_name,
-- record_id) with no tenant and no time, so it serves the single-record lookup
-- and nothing else.
--
-- `occurred_at DESC` in the index rather than relying on a backwards scan:
-- Postgres can read either direction, but naming it here documents that the
-- screen is newest-first and keeps the plan stable if a second sort key is ever
-- added.
CREATE INDEX IF NOT EXISTS "audit_log_tenant_table_time_idx"
	ON "audit_log" USING btree ("tenant_id", "table_name", "occurred_at" DESC);
